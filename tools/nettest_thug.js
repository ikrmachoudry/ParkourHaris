// Server-side Haris City thugs with 2 players: steal -> thug wakes, chases + punches, bat hits kill him.
import WebSocket from 'ws';
import { gtaCars } from '../public/js/gta.js';
const URL = 'ws://localhost:' + (process.env.PORT || 3998) + '/ws';
const mk = () => new Promise((res) => { const ws = new WebSocket(URL); const q = []; ws.msgs = q; ws.on('message', (d) => q.push(JSON.parse(d))); ws.on('open', () => res(ws)); });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const last = (ws, t) => [...ws.msgs].reverse().find((m) => m.t === t);
const has = (ws, f) => ws.msgs.some(f);
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const C = gtaCars()[2];
const P = [await mk(), await mk()];
P[0].send(JSON.stringify({ t: 'create', name: 'A', char: 0 })); await wait(150);
const code = last(P[0], 'joined').code;
P[1].send(JSON.stringify({ t: 'join', code, name: 'B', char: 1 })); await wait(150);
P[0].send(JSON.stringify({ t: 'level', level: 7 })); await wait(60); P[0].send(JSON.stringify({ t: 'start' })); await wait(120);
const go = last(P[1], 'go'); ok(go && go.level === 7, 'city starts');
await wait(go.t0 - Date.now() + 400);
const pos = (i, x, z) => P[i].send(JSON.stringify({ t: 's', x, y: 0, z, r: 0, a: 1, sp: 0, ts: Date.now(), rs: 0 }));
const hold = async (f, ms) => { for (let t = 0; t < ms; t += 100) { f(); await wait(100); } };
await hold(() => { pos(0, C.x, C.z + 3); pos(1, 80, 80); }, 400);
ok(last(P[1], 'th') && last(P[1], 'th').a.length === 8 && last(P[1], 'th').a.every((q) => q[0] === 0), 'all 8 thugs seated at start');
P[1].send(JSON.stringify({ t: 'steal', v: 2 })); await wait(200);
ok(last(P[0], 'th').a[2][0] === 0, 'a far-away player cannot steal');
P[0].send(JSON.stringify({ t: 'steal', v: 2 })); await hold(() => pos(0, C.x, C.z + 3), 600);
ok(last(P[1], 'th').a[2][0] === 1, 'steal wakes the thug (other player sees it)');
await hold(() => pos(0, C.x, C.z + 3), 1500);
ok(has(P[0], (m) => m.t === 'thev' && m.k === 'hit' && m.pid === last(P[0], 'joined').id), 'the thug punches the thief');
const th = () => last(P[0], 'th').a[2];
let n = 0;
while (th()[0] === 1 && n++ < 12) { pos(0, th()[2] - 1.5, th()[4]); await wait(100); P[0].send(JSON.stringify({ t: 'thit', v: 2, fx: 1, fz: 0 })); await wait(520); }
ok(th()[0] === 2, `bat hits kill the thug (${n} swings)`);
ok(n >= 4, 'it takes at least 4 hits');
console.log(fails ? 'NETTEST FAILURES' : 'NETTEST OK'); P.forEach((w) => w.close()); process.exit(fails ? 1 : 0);
