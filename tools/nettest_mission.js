import WebSocket from 'ws';
const URL = 'ws://localhost:' + (process.env.PORT || 3999) + '/ws';
const mk = () => new Promise((res) => { const ws = new WebSocket(URL); const q = []; ws.msgs = q; ws.on('message', (d) => q.push(JSON.parse(d))); ws.on('open', () => res(ws)); });
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
const last = (ws, t) => [...ws.msgs].reverse().find((m) => m.t === t);
const S = (ws, o) => ws.send(JSON.stringify(o));
let fails = 0; const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) fails++; };
const a = await mk(), b = await mk();
S(a, { t: 'create', name: 'A', char: 0 }); await wait(150);
const code = last(a, 'joined').code; S(b, { t: 'join', code, name: 'B', char: 1 }); await wait(100);
S(a, { t: 'level', level: 0 }); await wait(80); S(a, { t: 'start' }); await wait(100);
const go = last(b, 'go'); await wait(go.t0 - Date.now() + 200);
S(a, { t: 'm_in', on: true }); await wait(80);
ok(last(b, 'm_lobby') && last(b, 'm_lobby').in.length === 1 && last(b, 'm_lobby').total === 2, 'both see 1 of 2 on the lobby pad');
S(a, { t: 'm_start' }); await wait(80); ok(!last(a, 'm_go'), 'start refused while a player is missing');
S(b, { t: 'm_in', on: true }); await wait(80); S(b, { t: 'm_start' }); await wait(120);
ok(last(a, 'm_go') && last(b, 'm_go') && last(a, 'm_go').members.length === 2, 'everybody on the pad: mission starts for both');
await wait(6700); ok(last(a, 'm_run') && last(b, 'm_run'), 'countdown over: GO for both');
const rnd = last(a, 'm_go').round;
S(a, { t: 'm_res', ok: true, round: rnd }); await wait(80); ok(last(b, 'm_st') && !last(b, 'm_end'), 'one pass: the other is still running');
S(b, { t: 'm_res', ok: false, why: 'slow', round: rnd }); await wait(100);
ok(last(a, 'm_end') && last(a, 'm_end').pass === false && last(b, 'm_end').pass === false, 'one failure: FAILED for both');
await wait(4500); ok(last(a, 'm_go').round === rnd + 1 && last(b, 'm_go').round === rnd + 1, 'restarted for everybody');
await wait(6700); S(a, { t: 'm_res', ok: true, round: rnd + 1 }); S(b, { t: 'm_res', ok: true, round: rnd + 1 }); await wait(120);
ok(last(a, 'm_end').pass === true && last(b, 'm_end').pass === true, 'both pass: MISSION PASSED for both');
console.log(fails ? 'FAILED' : 'MISSION NET OK'); process.exit(fails ? 1 : 0);
